//! The stable registry of bundle keys (#43).
//!
//! Every struct field and enum variant name the bundle encodes has a small
//! integer here, used in place of the name. An ID is never reused or
//! renumbered: a new field or variant gets the next free ID, and a removed
//! one keeps its entry. `tests/golden/bundle-keys.txt` holds every ID
//! ever published, and a test fails if one changes meaning.
//!
//! The sign of an ID says what a reader that does not know it must do when
//! it appears as a map key:
//!
//! - **critical** (0 and up): the reader refuses the bundle, because it
//!   cannot tell how the field changes decisions;
//! - **ignorable** (below 0): the reader skips the entry. Only fields that
//!   never change a decision, such as descriptions, are ignorable.
//!
//! As a value (an enum variant), an unknown ID is always refused.
//!
//! Names are one namespace: `name` is the same key in a rule, a rule set
//! and a location profile. A name that is critical anywhere is critical
//! everywhere.

use std::collections::BTreeMap;
use std::sync::LazyLock;

/// One registered key.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Key {
    /// The integer written in the bundle.
    pub id: i64,
    /// The field or variant name in the policy model, as serde writes it.
    pub name: &'static str,
    /// The first bundle format version that has it.
    pub since: u16,
}

impl Key {
    /// Whether a reader that does not know the key must refuse the bundle.
    #[must_use]
    pub const fn critical(&self) -> bool {
        self.id >= 0
    }
}

const fn k(id: i64, name: &'static str) -> Key {
    Key { id, name, since: 1 }
}

