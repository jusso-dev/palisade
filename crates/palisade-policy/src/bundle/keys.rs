static BY_NAME: LazyLock<BTreeMap<&'static str, i64>> =
    LazyLock::new(|| KEYS.iter().map(|k| (k.name, k.id)).collect());

static BY_ID: LazyLock<BTreeMap<i64, &'static str>> =
    LazyLock::new(|| KEYS.iter().map(|k| (k.id, k.name)).collect());

/// The ID of a name, if it is registered.
#[must_use]
pub fn id(name: &str) -> Option<i64> {
    BY_NAME.get(name).copied()
}

/// The name of an ID, if it is registered.
#[must_use]
pub fn name(id: i64) -> Option<&'static str> {
    BY_ID.get(&id).copied()
}

