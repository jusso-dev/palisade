//! The Authenticode PE image hash (#47).
//!
//! The Authenticode hash identifies a PE image independently of its embedded
//! signature. It covers every byte of the file except three regions:
//!
//! 1. the 4-byte `CheckSum` field of the optional header;
//! 2. the 8-byte certificate table (security) entry in the data directories;
//! 3. the certificate table itself, located by that entry.
//!
//! So the hash stays the same when a file is signed, re-signed or has its
//! signature stripped, and any other byte change changes it.
//!
//! # How the bytes are chosen
//!
//! [`HashRanges::from_pe`] turns a [`PeInfo`] from [`crate::pe::parse`] into
//! the list of file ranges to hash: the whole file in file order, minus the
//! three regions above. It reuses the parser's certificate table location,
//! so a table the parser rejected is never excluded. [`RangeHasher`] then
//! streams the file through those ranges in a single pass.
//!
//! The Authenticode specification describes the hash section by section:
//! the headers up to `SizeOfHeaders`, then each section's raw data sorted by
//! `PointerToRawData` (skipping sections with no raw data), then any data
//! after the last section up to the certificate table. For a conformant
//! image, where the sections follow the headers and each other with no gaps
//! or overlaps and the certificate table is the last thing in the file, that
//! is exactly "every byte before the certificate table, in file order, minus
//! the two header fields". [`HashRanges::from_pe`] checks that layout and
//! reports any departure as [`AuthenticodeStatus::NonConformant`].
//!
//! For a non-conformant image the specification's steps either read bytes
//! twice, skip bytes, or read past the end of the file, and implementations
//! disagree. The digest returned is then a best effort that still covers
//! every byte outside the three regions. The OS treats such files by their
//! flat hash, so policy must too (#55).
//!
//! # What the hash does not cover
//!
//! Because the certificate table is excluded, bytes stored inside it can be
//! changed without changing the Authenticode hash. Signature verification
//! (#48) checks the `WIN_CERTIFICATE` entries; anything else in the table is
//! not part of the file's identity. Rules that must cover every byte use the
//! flat hash.
//!
//! # Padding
//!
//! A signer pads an image with zero bytes to a multiple of 8 before it
//! appends the certificate table, because the table must start on an 8-byte
//! boundary. Those padding bytes are part of the signed file and are hashed.
//! When an image has **no** certificate table and its length is not a
//! multiple of 8, the hash therefore includes the same zero padding (1 to 7
//! bytes) after the last byte, so the digest equals the one the image will
//! have once signed. One consequence: an unsigned image and the same image
//! with those zero bytes actually appended have the same Authenticode digest.
//! Their flat hashes differ.
//!
//! # Algorithms
//!
//! [`authenticode_hashes`] always computes SHA-256 and SHA-1, and any other
//! algorithm in the set it is given. SHA-1 (and MD5) are **not collision
//! resistant** and exist only to match older signatures and OS policy
//! rules; they must never be the sole basis of an allow decision (ADR 0008).
//!
//! # Not here yet
//!
//! - Page hash tables and the code-integrity "page hash" rule value (#47).
//!   Their construction is not fully specified, so they wait for fixtures
//!   generated by OS tooling.
//! - Comparing the digest with a signature's embedded digest
//!   (`DigestMismatch`), which needs signature parsing (#48).
//! - Reading a file from disk. [`RangeHasher`] takes the file's bytes in
//!   order, so a reader can feed one buffer to it and to the flat-hash
//!   [`MultiHasher`] in a single pass; the file-level entry point waits for
//!   the `ReadAt` abstraction (#45).

#![forbid(unsafe_code)]

use std::fmt;

use crate::hash::{AlgorithmSet, Digest, HashAlgorithm, MultiHasher};
use crate::pe::{self, DataDirectoryKind, FileRange, ParseOptions, PeInfo, WarningKind};

/// Size of the `CheckSum` field.
const CHECKSUM_SIZE: u64 = 4;
/// Size of one data directory entry.
const DIRECTORY_ENTRY_SIZE: u64 = 8;
/// Size of one section header.
const SECTION_HEADER_SIZE: u64 = 40;
/// The certificate table starts on, and signers pad to, this boundary.
const CERTIFICATE_ALIGNMENT: u64 = 8;

/// The load context an OS policy hash rule applies to.
///
/// OS policy tooling emits each hash rule twice, once for user-mode and once
/// for kernel-mode code, when it does not know how a file will be loaded.
/// **The digest is the same in both cases.** The scenario is metadata on the
/// rule, for the policy compilers (#6); nothing in this module computes a
/// different hash per scenario.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum HashScenario {
    /// User-mode code (applications, DLLs, scripts hosts).
    UserMode,
    /// Kernel-mode code (drivers).
    KernelMode,
}

impl HashScenario {
    /// Both scenarios, in the order rules are emitted.
    pub const ALL: [Self; 2] = [Self::UserMode, Self::KernelMode];
}

/// Whether an image's layout is one the Authenticode specification
/// describes, so that the digest is the one every implementation computes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AuthenticodeStatus {
    /// The layout follows the specification. The digest is authoritative.
    Conformant,
    /// The layout departs from the specification in these ways (at least
    /// one, at most one per kind of check). The digest is a best effort over
    /// every byte outside the excluded regions; use the flat hash as the
    /// file's identity (#55).
    NonConformant(Vec<NonConformance>),
}

impl AuthenticodeStatus {
    /// Whether the status is [`AuthenticodeStatus::Conformant`].
    #[must_use]
    pub const fn is_conformant(&self) -> bool {
        matches!(self, Self::Conformant)
    }

    /// The reasons the image is not conformant; empty when it is.
    #[must_use]
    pub fn reasons(&self) -> &[NonConformance] {
        match self {
            Self::Conformant => &[],
            Self::NonConformant(reasons) => reasons,
        }
    }
}

/// One way an image's layout departs from the Authenticode specification.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum NonConformance {
    /// The optional header has no certificate table entry
    /// (`NumberOfRvaAndSizes` is below 5, or the header is too small). The
    /// bytes where it would be are hashed like any others.
    NoSecurityDirectoryEntry,
    /// Fewer section headers were read than `NumberOfSections` declares
    /// (the table is cut off, or over [`pe::MAX_SECTIONS`]), so the layout
    /// could not be checked in full.
    SectionTableIncomplete {
        /// `NumberOfSections`.
        declared: u16,
        /// Section headers read.
        parsed: u16,
    },
    /// `SizeOfHeaders` ends before the section table does, so the
    /// specification's header step would leave part of the table out.
    SizeOfHeadersTooSmall {
        /// `SizeOfHeaders`.
        size_of_headers: u32,
        /// File offset where the section table ends.
        headers_end: u64,
    },
    /// `SizeOfHeaders` is larger than the file.
    HeadersOutOfFile {
        /// `SizeOfHeaders`.
        size_of_headers: u32,
    },
    /// Taken in `PointerToRawData` order, a section's raw data does not
    /// start where the headers or the previous section end: there is a gap
    /// (`pointer_to_raw_data > expected`) or an overlap (`<`). Only the
    /// first such section is reported.
    SectionNotContiguous {
        /// Index of the section in the section table.
        index: u16,
        /// Where its data should start.
        expected: u64,
        /// Its `PointerToRawData`.
        pointer_to_raw_data: u32,
    },
    /// A section's raw data runs past the end of the file.
    SectionOutOfFile {
        /// Index of the section in the section table.
        index: u16,
    },
    /// The certificate table entry is non-zero but the parser did not accept
    /// it as a certificate table (it points into the headers, runs past the
    /// end of the file or overlaps a section). Nothing is excluded for it.
    CertificateTableRejected {
        /// The entry's file offset field.
        offset: u32,
        /// The entry's size field.
        size: u32,
        /// The parser's reason ([`PeInfo::certificate_table_issue`]).
        reason: Option<WarningKind>,
    },
    /// The certificate table starts before the end of the section data as
    /// the specification reads it (`PointerToRawData + SizeOfRawData` of the
    /// last section). This happens when a section's pointer is not
    /// sector-aligned: the loader, and so the parser, rounds it down, but
    /// the specification's steps use it as written.
    CertificateTableInsideSectionData {
        /// The table's file offset.
        offset: u64,
        /// Where the section data ends.
        sections_end: u64,
    },
    /// The certificate table does not start on an 8-byte boundary.
    CertificateTableMisaligned {
        /// Its file offset.
        offset: u64,
    },
    /// Data follows the certificate table. It is hashed, but a signer never
    /// covered it, so a signature's digest will not match.
    DataAfterCertificateTable {
        /// File offset where the extra data starts.
        offset: u64,
        /// Its size in bytes.
        size: u64,
    },
}

impl fmt::Display for NonConformance {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::NoSecurityDirectoryEntry => {
                f.write_str("the optional header has no certificate table entry")
            }
            Self::SectionTableIncomplete { declared, parsed } => {
                write!(f, "only {parsed} of {declared} section headers were read")
            }
            Self::SizeOfHeadersTooSmall {
                size_of_headers,
                headers_end,
            } => write!(
                f,
                "SizeOfHeaders {size_of_headers:#x} ends before the section table ({headers_end:#x})"
            ),
            Self::HeadersOutOfFile { size_of_headers } => {
                write!(
                    f,
                    "SizeOfHeaders {size_of_headers:#x} is past the end of the file"
                )
            }
            Self::SectionNotContiguous {
                index,
                expected,
                pointer_to_raw_data,
            } => write!(
                f,
                "section {index} starts at {pointer_to_raw_data:#x}, not at {expected:#x}"
            ),
            Self::SectionOutOfFile { index } => {
                write!(f, "section {index} runs past the end of the file")
            }
            Self::CertificateTableRejected { offset, size, .. } => write!(
                f,
                "the certificate table entry ({offset:#x}, {size:#x}) is not a valid table"
            ),
            Self::CertificateTableInsideSectionData {
                offset,
                sections_end,
            } => write!(
                f,
                "the certificate table at {offset:#x} starts before the section data ends ({sections_end:#x})"
            ),
            Self::CertificateTableMisaligned { offset } => {
                write!(
                    f,
                    "the certificate table at {offset:#x} is not 8-byte aligned"
                )
            }
            Self::DataAfterCertificateTable { offset, size } => {
                write!(
                    f,
                    "{size} bytes follow the certificate table at {offset:#x}"
                )
            }
        }
    }
}

/// The byte ranges of one image that the Authenticode hash covers, built
/// once from the parse with [`HashRanges::from_pe`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HashRanges {
    file_size: u64,
    /// Sorted, disjoint, non-empty and inside the file. At most four: the
    /// three excluded regions split the file into at most four parts.
    included: Vec<FileRange>,
    padding: u64,
    status: AuthenticodeStatus,
}

impl HashRanges {
    /// Works out which bytes of the image `info` describes are hashed, and
    /// whether its layout conforms to the specification.
    ///
    /// Only `info` is used; no file data is read. Every offset is clamped to
    /// [`PeInfo::file_size`], so the ranges always lie inside the file even
    /// for a hand-built `info`.
    #[must_use]
    pub fn from_pe(info: &PeInfo) -> Self {
        let file_size = info.file_size;
        let mut reasons = Vec::new();

        let mut excluded = Vec::with_capacity(3);
        excluded.push(FileRange {
            offset: info.optional.checksum_offset,
            size: CHECKSUM_SIZE,
        });
        // The entry is excluded whatever it holds, even zero, because a
        // signer writes it after hashing. If the header has no room for it
        // the bytes there belong to something else and stay hashed.
        let security = info
            .data_directories
            .get(DataDirectoryKind::Security.index());
        match security {
            Some(entry) => excluded.push(FileRange {
                offset: entry.entry_offset,
                size: DIRECTORY_ENTRY_SIZE,
            }),
            None => reasons.push(NonConformance::NoSecurityDirectoryEntry),
        }
        match (info.certificate_table, security) {
            (Some(table), _) => {
                excluded.push(table);
                if table.offset % CERTIFICATE_ALIGNMENT != 0 {
                    reasons.push(NonConformance::CertificateTableMisaligned {
                        offset: table.offset,
                    });
                }
                let end = table.offset.saturating_add(table.size);
                if end < file_size {
                    reasons.push(NonConformance::DataAfterCertificateTable {
                        offset: end,
                        size: file_size - end,
                    });
                }
            }
            // A zero size means "no certificate table", whatever the offset.
            (None, Some(entry)) if entry.size != 0 => {
                reasons.push(NonConformance::CertificateTableRejected {
                    offset: entry.virtual_address,
                    size: entry.size,
                    reason: info.certificate_table_issue.clone(),
                });
            }
            (None, _) => {}
        }

        let sections_end = check_layout(info, &mut reasons);
        if let (Some(table), Some(end)) = (info.certificate_table, sections_end) {
            if table.offset < end {
                reasons.push(NonConformance::CertificateTableInsideSectionData {
                    offset: table.offset,
                    sections_end: end,
                });
            }
        }

        excluded.sort_by_key(|r| r.offset);
        let mut included = Vec::with_capacity(excluded.len() + 1);
        let mut cursor = 0_u64;
        for range in &excluded {
            let start = range.offset.min(file_size);
            if start > cursor {
                included.push(FileRange {
                    offset: cursor,
                    size: start - cursor,
                });
            }
            cursor = cursor.max(range.offset.saturating_add(range.size).min(file_size));
        }
        if cursor < file_size {
            included.push(FileRange {
                offset: cursor,
                size: file_size - cursor,
            });
        }

        let padding = if info.certificate_table.is_some() {
            0
        } else {
            (CERTIFICATE_ALIGNMENT - file_size % CERTIFICATE_ALIGNMENT) % CERTIFICATE_ALIGNMENT
        };

        let status = if reasons.is_empty() {
            AuthenticodeStatus::Conformant
        } else {
            AuthenticodeStatus::NonConformant(reasons)
        };
        Self {
            file_size,
            included,
            padding,
            status,
        }
    }

    /// The length of the file the ranges were built for.
    #[must_use]
    pub const fn file_size(&self) -> u64 {
        self.file_size
    }

    /// The file ranges that are hashed, in file order. They are disjoint,
    /// non-empty and inside the file.
    #[must_use]
    pub fn included(&self) -> &[FileRange] {
        &self.included
    }

    /// The number of zero bytes hashed after the last range (0 to 7): the
    /// padding a signer would add before appending a certificate table.
    /// Always zero when the image has a certificate table.
    #[must_use]
    pub const fn padding(&self) -> u64 {
        self.padding
    }

    /// Whether the layout conforms to the specification.
    #[must_use]
    pub const fn status(&self) -> &AuthenticodeStatus {
        &self.status
    }
}

/// Checks the layout the specification's section-by-section steps assume:
/// the headers, then each section's raw data in `PointerToRawData` order with
/// no gaps or overlaps, all inside the file. At most one reason is recorded
/// for the headers and one for the sections.
///
/// Returns where the specification's section step ends (the end of the last
/// section's raw data, or `SizeOfHeaders`), or `None` if the sections are
/// not laid out that way.
fn check_layout(info: &PeInfo, reasons: &mut Vec<NonConformance>) -> Option<u64> {
    let file_size = info.file_size;
    let parsed = u16::try_from(info.sections.len()).unwrap_or(u16::MAX);
    if parsed < info.coff.number_of_sections {
        reasons.push(NonConformance::SectionTableIncomplete {
            declared: info.coff.number_of_sections,
            parsed,
        });
    }

    let size_of_headers = info.optional.size_of_headers;
    let table_start = info
        .optional
        .offset
        .saturating_add(u64::from(info.coff.size_of_optional_header));
    let headers_end = info.sections.last().map_or(table_start, |s| {
        s.header_offset.saturating_add(SECTION_HEADER_SIZE)
    });
    if u64::from(size_of_headers) < headers_end {
        reasons.push(NonConformance::SizeOfHeadersTooSmall {
            size_of_headers,
            headers_end,
        });
    } else if u64::from(size_of_headers) > file_size {
        reasons.push(NonConformance::HeadersOutOfFile { size_of_headers });
    }

    // `sections` is bounded by `MAX_SECTIONS`, so this allocation is too.
    let mut with_data: Vec<(u32, u32, u16)> = info
        .sections
        .iter()
        .enumerate()
        .filter(|(_, s)| s.size_of_raw_data != 0)
        .map(|(i, s)| {
            (
                s.pointer_to_raw_data,
                s.size_of_raw_data,
                u16::try_from(i).unwrap_or(u16::MAX),
            )
        })
        .collect();
    // Stable, so sections with the same pointer keep table order.
    with_data.sort_by_key(|(pointer, _, _)| *pointer);
    let mut cursor = u64::from(size_of_headers);
    for (pointer, size, index) in with_data {
        if u64::from(pointer) != cursor {
            reasons.push(NonConformance::SectionNotContiguous {
                index,
                expected: cursor,
                pointer_to_raw_data: pointer,
            });
            return None;
        }
        let end = u64::from(pointer) + u64::from(size);
        if end > file_size {
            reasons.push(NonConformance::SectionOutOfFile { index });
            return None;
        }
        cursor = end;
    }
    Some(cursor)
}

/// Why an Authenticode hash could not be computed.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum AuthenticodeError {
    /// The data hashed is not the length of the file the ranges were built
    /// for, so it is not that file.
    LengthMismatch {
        /// [`HashRanges::file_size`].
        expected: u64,
        /// Bytes supplied.
        actual: u64,
    },
}

impl fmt::Display for AuthenticodeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::LengthMismatch { expected, actual } => write!(
                f,
                "expected {expected} bytes of image data for the Authenticode hash, got {actual}"
            ),
        }
    }
}

impl std::error::Error for AuthenticodeError {}

/// The Authenticode hashes of one image.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AuthenticodeHashes {
    /// One digest per algorithm computed, in [`HashAlgorithm::ALL`] order.
    pub digests: Vec<Digest>,
    /// Bytes fed to each hash, including any zero padding.
    pub hashed_bytes: u64,
    /// Whether the layout conforms to the specification. When it does not,
    /// the digests are a best effort and the flat hash is authoritative.
    pub status: AuthenticodeStatus,
}

impl AuthenticodeHashes {
    /// The digest for `alg`, if it was computed.
    #[must_use]
    pub fn get(&self, alg: HashAlgorithm) -> Option<&Digest> {
        self.digests.iter().find(|d| d.algorithm() == alg)
    }

    /// The SHA-256 digest. Always present from [`authenticode_hashes`] and
    /// [`hash_pe`]; present from a [`RangeHasher`] only if it was asked for.
    #[must_use]
    pub fn sha256(&self) -> Option<&Digest> {
        self.get(HashAlgorithm::Sha256)
    }

    /// The SHA-1 digest, for matching older signatures and OS policy rules.
    /// **Not collision resistant.** Present when [`Self::sha256`] is.
    #[must_use]
    pub fn sha1(&self) -> Option<&Digest> {
        self.get(HashAlgorithm::Sha1)
    }
}

/// Streams an image through its [`HashRanges`], in one pass.
///
/// Feed the whole file, in order, from offset 0, in chunks of any size; only
/// the included bytes reach the hashes. The same chunks can be fed to a
/// [`MultiHasher`] for the flat hashes at the same time, so one read of the
/// file yields both:
///
/// ```
/// use palisade_fileid::authenticode::{HashRanges, RangeHasher};
/// use palisade_fileid::hash::{AlgorithmSet, MultiHasher};
/// # fn demo(data: &[u8]) -> Option<()> {
/// let info = palisade_fileid::pe::parse(data).ok()?;
/// let mut image = RangeHasher::new(HashRanges::from_pe(&info), AlgorithmSet::SHA256);
/// let mut flat = MultiHasher::new(AlgorithmSet::SHA256);
/// for chunk in data.chunks(64 * 1024) {
///     image.update(chunk);
///     flat.update(chunk);
/// }
/// let (image, flat) = (image.finalize().ok()?, flat.finalize());
/// # let _ = (image, flat);
/// # Some(())
/// # }
/// ```
#[derive(Debug, Clone)]
pub struct RangeHasher {
    ranges: HashRanges,
    hasher: MultiHasher,
    position: u64,
}

impl RangeHasher {
    /// A hasher for the algorithms in `set` over `ranges`.
    #[must_use]
    pub fn new(ranges: HashRanges, set: AlgorithmSet) -> Self {
        Self {
            ranges,
            hasher: MultiHasher::new(set),
            position: 0,
        }
    }

    /// Feeds the next chunk of the file.
    pub fn update(&mut self, chunk: &[u8]) {
        let start = self.position;
        let end = start.saturating_add(u64::try_from(chunk.len()).unwrap_or(u64::MAX));
        for range in &self.ranges.included {
            let from = range.offset.max(start);
            let to = range.offset.saturating_add(range.size).min(end);
            if from >= to {
                continue;
            }
            // `start <= from < to <= end`, so both fit in the chunk.
            let (Ok(a), Ok(b)) = (usize::try_from(from - start), usize::try_from(to - start))
            else {
                continue;
            };
            if let Some(part) = chunk.get(a..b) {
                self.hasher.update(part);
            }
        }
        self.position = end;
    }

    /// Finishes the hashes. Fails if the bytes fed are not exactly
    /// [`HashRanges::file_size`] long.
    pub fn finalize(mut self) -> Result<AuthenticodeHashes, AuthenticodeError> {
        if self.position != self.ranges.file_size {
            return Err(AuthenticodeError::LengthMismatch {
                expected: self.ranges.file_size,
                actual: self.position,
            });
        }
        let zeros = [0_u8; 8];
        let padding = usize::try_from(self.ranges.padding).unwrap_or(0);
        self.hasher.update(zeros.get(..padding).unwrap_or_default());
        let hashed_bytes = self.hasher.bytes_hashed();
        Ok(AuthenticodeHashes {
            digests: self.hasher.finalize().digests,
            hashed_bytes,
            status: self.ranges.status,
        })
    }
}

/// The Authenticode hashes of `data`, the image `info` was parsed from.
///
/// This is the issue's `authenticode_digest(pe, alg)`. SHA-256 and SHA-1
/// are always computed, plus any other algorithm in `extra`; pick one with
/// [`AuthenticodeHashes::get`]. Check [`AuthenticodeHashes::status`] before
/// treating a digest as authoritative. Fails if `data` is not the length
/// `info` was parsed from.
pub fn authenticode_hashes(
    data: &[u8],
    info: &PeInfo,
    extra: AlgorithmSet,
) -> Result<AuthenticodeHashes, AuthenticodeError> {
    let actual = u64::try_from(data.len()).unwrap_or(u64::MAX);
    if actual != info.file_size {
        return Err(AuthenticodeError::LengthMismatch {
            expected: info.file_size,
            actual,
        });
    }
    let set = extra | AlgorithmSet::SHA256 | AlgorithmSet::SHA1;
    let mut hasher = RangeHasher::new(HashRanges::from_pe(info), set);
    hasher.update(data);
    hasher.finalize()
}

/// Parses `data` as a PE image and returns its Authenticode hashes, as
/// [`authenticode_hashes`] does, or `None` if it is not a PE image.
///
/// Only the headers are parsed ([`ParseOptions::metadata_only`]). Script,
/// MSI and catalog digests are other formats (#51, #52, #53).
#[must_use]
pub fn hash_pe(data: &[u8], extra: AlgorithmSet) -> Option<AuthenticodeHashes> {
    let info = pe::parse_with(data, &ParseOptions::metadata_only()).ok()?;
    authenticode_hashes(data, &info, extra).ok()
}
