//! `cargo xtask check-unsafe`: where `unsafe` code may be allowed.
//!
//! The policy is in ADR 0011 (`docs/adr/0011-msrv-and-unsafe-code-policy.md`).
//! The compiler does most of the work: the workspace sets
//! `unsafe_code = "forbid"`, so `unsafe` anywhere fails to build. This check
//! is the second layer, which still holds once the workspace lowers the lint
//! to `deny` for the first FFI module. It fails when:
//!
//! - a Rust file relaxes the `unsafe_code` lint (`allow`, `expect` or `warn`
//!   naming the lint in the same attribute, as an inner or outer attribute,
//!   including inside `cfg_attr` and macro bodies) and is not listed in
//!   `unsafe-allowlist.txt`;
//! - `unsafe-allowlist.txt` lists a file that does not relax the lint, does
//!   not exist, is listed twice, or is outside the locations ADR 0011 allows
//!   ([`ALLOWED_LOCATIONS`]);
//! - a crate in [`FORBID_AT_ROOT`] has a library or binary root without a
//!   crate-level `#![forbid(unsafe_code)]`;
//! - a file is a symbolic link (in the working tree, or recorded as one in
//!   the git index), a listed file cannot be inspected, or a Rust file cannot
//!   be tokenised;
//! - the root `Cargo.toml` sets `unsafe_code` to anything but `forbid` or
//!   `deny`, or spells it a second way (`unsafe-code`);
//! - a Cargo config file in the repository (`.cargo/config.toml` or the
//!   legacy `.cargo/config`, in any letter case) sets anything but plain
//!   aliases ([`ALLOWED_CARGO_CONFIG_TABLES`]), or an alias changes lints,
//!   config or compiler flags ([`check_cargo_config`]).
//!
//! The files scanned are every `.rs` file git tracks or would track (tracked
//! plus untracked, minus ignored ones), so build output is skipped by the same
//! rules as commits, not by directory name. Each file is tokenised with
//! `proc-macro2`, the same tokeniser procedural macros use, so comments and
//! literals are never mistaken for attributes.
//!
//! Limits, which review covers: a macro that builds the attribute from its
//! parameters (`#[$a($b)]`), a module loaded with `#[path]` or `include!`
//! from a file that is untracked or not named `.rs`, and code generated by a build script
//! into `OUT_DIR`. The workspace `forbid` still applies to all of them.

use std::{path::Path, process::Command, str::FromStr};

use proc_macro2::{Delimiter, TokenStream, TokenTree};

/// Repository-relative path prefixes where ADR 0011 allows a file to relax
/// `unsafe_code`. A prefix ending in `/` covers a directory (a module and its
/// submodules); one ending in `.rs` is a single module file.
pub const ALLOWED_LOCATIONS: &[&str] = &[
    "crates/palisade-agent/src/ffi.rs",
    "crates/palisade-agent/src/ffi/",
    "crates/palisade-tray/src/ffi.rs",
    "crates/palisade-tray/src/ffi/",
    "crates/palisade-fileid/src/win.rs",
    "crates/palisade-fileid/src/win/",
    "crates/palisade-driver/",
];

/// Crates that have no allowlisted module, so ADR 0011 requires
/// `#![forbid(unsafe_code)]` at the root of their library and binaries.
pub const FORBID_AT_ROOT: &[&str] = &[
    "palisade-core",
    "palisade-policy",
    "palisade-proto",
    "palisade-server",
    "palisade-console",
    "palisade-cli",
    "xtask",
];

/// Cargo config files Cargo reads from a directory's `.cargo/`.
pub const CARGO_CONFIG_FILES: &[&str] = &[".cargo/config.toml", ".cargo/config"];

/// Every file git tracks or would track under `root` (tracked and untracked,
/// without ignored files), as repository-relative paths with `/` separators,
/// sorted. Symbolic links are reported as violations, because a link could
/// point the check away from the code the compiler reads. A tracked path is
/// a link if the git index records it as one (mode `120000`), even where
/// `core.symlinks=false` checked it out as a regular file, or if it is a
/// link in the working tree.
pub fn repository_files(root: &Path) -> Result<(Vec<String>, Vec<String>), String> {
    // `--stage` prints `<mode> <object> <stage>\t<path>` for each index entry.
    let mut entries: Vec<(String, bool)> = Vec::new();
    for entry in git_ls_files(root, &["--cached", "--stage"])? {
        let (info, path) = entry
            .split_once('\t')
            .ok_or_else(|| format!("unexpected git ls-files --stage line: {entry}"))?;
        let in_index_as_link = info.starts_with("120000 ");
        match entries.last_mut() {
            // A conflicted path has one entry per stage, one after another.
            Some((last, link)) if last == path => *link |= in_index_as_link,
            _ => entries.push((path.to_owned(), in_index_as_link)),
        }
    }
    for path in git_ls_files(root, &["--others", "--exclude-standard"])? {
        entries.push((path, false));
    }
    let mut files = Vec::new();
    let mut violations = Vec::new();
    for (path, in_index_as_link) in entries {
        let on_disk =
            std::fs::symlink_metadata(root.join(&path)).map(|m| m.file_type().is_symlink());
        match classify(&path, in_index_as_link, on_disk)? {
            Entry::File => files.push(path),
            Entry::Link => violations.push(format!(
                "{path} is a symbolic link; check-unsafe cannot vouch for what it points to"
            )),
            Entry::Deleted => {}
        }
    }
    files.sort();
    Ok((files, violations))
}

/// The variables `git rev-parse --local-env-vars` lists: they point git at a
/// particular repository, index or object store whatever the working
/// directory. A git hook exports some of them (`GIT_DIR`, `GIT_INDEX_FILE`),
/// so `cargo xtask check-unsafe` or `cargo test` run from a hook would
/// otherwise read the hook's repository instead of the one at `root`.
const GIT_LOCAL_ENV_VARS: &[&str] = &[
    "GIT_ALTERNATE_OBJECT_DIRECTORIES",
    "GIT_COMMON_DIR",
    "GIT_CONFIG",
    "GIT_CONFIG_COUNT",
    "GIT_CONFIG_PARAMETERS",
    "GIT_DIR",
    "GIT_GRAFT_FILE",
    "GIT_IMPLICIT_WORK_TREE",
    "GIT_INDEX_FILE",
    "GIT_NO_REPLACE_OBJECTS",
    "GIT_OBJECT_DIRECTORY",
    "GIT_PREFIX",
    "GIT_REPLACE_REF_BASE",
    "GIT_SHALLOW_FILE",
    "GIT_WORK_TREE",
];

/// `git`, run in `dir`, finding the repository from `dir` alone: the
/// [`GIT_LOCAL_ENV_VARS`] are removed from its environment (not from this
/// process's, which tests share). The rest of the environment is kept.
fn git_in(dir: &Path) -> Command {
    let mut git = Command::new("git");
    git.current_dir(dir);
    for name in GIT_LOCAL_ENV_VARS {
        git.env_remove(name);
    }
    git
}

fn git_ls_files(root: &Path, args: &[&str]) -> Result<Vec<String>, String> {
    let output = git_in(root)
        .args(["ls-files", "-z"])
        .args(args)
        .output()
        .map_err(|e| format!("cannot run git ls-files: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "git ls-files failed: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        ));
    }
    output
        .stdout
        .split(|b| *b == 0)
        .filter(|p| !p.is_empty())
        .map(|p| {
            String::from_utf8(p.to_vec())
                .map_err(|_| "git ls-files returned a path that is not UTF-8".to_owned())
        })
        .collect()
}

/// What a listed path is.
#[derive(Debug, PartialEq)]
enum Entry {
    File,
    Link,
    /// Tracked, but deleted in the working tree, so not compiled.
    Deleted,
}

/// `on_disk` is whether the working-tree path is a symbolic link. Only a
/// missing path is skipped; any other error (such as permission denied)
/// fails the check, so a file is never left out unseen.
fn classify(
    path: &str,
    in_index_as_link: bool,
    on_disk: std::io::Result<bool>,
) -> Result<Entry, String> {
    if in_index_as_link {
        return Ok(Entry::Link);
    }
    match on_disk {
        Ok(true) => Ok(Entry::Link),
        Ok(false) => Ok(Entry::File),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Entry::Deleted),
        Err(e) => Err(format!("cannot inspect {path}: {e}")),
    }
}

/// Entries of `unsafe-allowlist.txt`: one repository-relative path per line.
/// Blank lines and lines starting with `#` are ignored.
pub fn parse_allowlist(source: &str) -> Vec<String> {
    source
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(str::to_owned)
        .collect()
}

/// Compares the Rust files that relax `unsafe_code` with the allowlist.
/// `files` maps each repository-relative `.rs` path to its source.
pub fn check_files(files: &[(String, String)], allowlist: &[String]) -> Vec<String> {
    let mut v = Vec::new();
    let mut relaxing: Vec<&str> = Vec::new();
    for (path, source) in files {
        match relaxes_unsafe_code(source) {
            Ok(true) => relaxing.push(path),
            Ok(false) => {}
            Err(error) => v.push(format!(
                "{path}: cannot tokenise ({error}); check-unsafe fails closed"
            )),
        }
    }

    for path in &relaxing {
        if !allowlist.iter().any(|a| a == path) {
            v.push(format!(
                "{path} allows unsafe code but is not listed in unsafe-allowlist.txt (ADR 0011)"
            ));
        }
    }

    let mut seen: Vec<&str> = Vec::new();
    for entry in allowlist {
        if seen.contains(&entry.as_str()) {
            v.push(format!("unsafe-allowlist.txt lists {entry} twice"));
            continue;
        }
        seen.push(entry);
        if !is_allowed_location(entry) {
            v.push(format!(
                "unsafe-allowlist.txt lists {entry}, which is outside the locations ADR 0011 allows: {}",
                ALLOWED_LOCATIONS.join(", ")
            ));
        }
        if !files.iter().any(|(path, _)| path == entry) {
            v.push(format!(
                "unsafe-allowlist.txt lists {entry}, which is not a Rust file in the repository"
            ));
        } else if !relaxing.contains(&entry.as_str()) {
            v.push(format!(
                "unsafe-allowlist.txt lists {entry}, which does not allow unsafe code; remove the entry"
            ));
        }
    }
    v
}

/// `path` is under one of [`ALLOWED_LOCATIONS`].
pub fn is_allowed_location(path: &str) -> bool {
    !path.split('/').any(|part| part == ".." || part == ".")
        && ALLOWED_LOCATIONS.iter().any(|loc| {
            if loc.ends_with('/') {
                path.starts_with(loc)
            } else {
                path == *loc
            }
        })
}

/// `true` when the source has an attribute, anywhere, that relaxes
/// `unsafe_code`.
pub fn relaxes_unsafe_code(source: &str) -> Result<bool, String> {
    let tokens = tokenize(source)?;
    let mut found = false;
    visit_attributes(tokens, &mut |attribute| {
        found |= attribute.relaxes_unsafe_code();
    });
    Ok(found)
}

/// `true` when the crate-level inner attributes (the `#![...]` before the
/// first item) include `forbid` with `unsafe_code` among its lints.
pub fn forbids_unsafe_code(source: &str) -> Result<bool, String> {
    let tokens: Vec<TokenTree> = tokenize(source)?.into_iter().collect();
    let mut i = 0;
    while let Some(attribute) = inner_attribute_at(&tokens, i) {
        if attribute.is_forbid_unsafe_code() {
            return Ok(true);
        }
        i += 3;
    }
    Ok(false)
}

/// The workspace lint level from the root `Cargo.toml` must be `forbid` or
/// `deny`, under exactly one spelling.
pub fn check_workspace_lint(root_manifest: &str) -> Result<Vec<String>, String> {
    let manifest: toml::Table = root_manifest
        .parse()
        .map_err(|e| format!("Cargo.toml: invalid TOML: {e}"))?;
    let rust = manifest
        .get("workspace")
        .and_then(|w| w.get("lints"))
        .and_then(|l| l.get("rust"))
        .and_then(toml::Value::as_table);
    let mut v = Vec::new();
    let spellings: Vec<(&String, &toml::Value)> = rust
        .into_iter()
        .flatten()
        .filter(|(k, _)| is_unsafe_code_lint(k))
        .collect();
    if spellings.len() > 1 {
        v.push(
            "Cargo.toml: [workspace.lints.rust] sets the unsafe_code lint more than once (as `unsafe_code` and `unsafe-code`)"
                .to_owned(),
        );
    }
    let level = |value: &toml::Value| match value {
        toml::Value::String(s) => Some(s.clone()),
        toml::Value::Table(t) => t
            .get("level")
            .and_then(toml::Value::as_str)
            .map(str::to_owned),
        _ => None,
    };
    let ok = !spellings.is_empty()
        && spellings
            .iter()
            .all(|(_, value)| matches!(level(value).as_deref(), Some("forbid" | "deny")));
    if !ok {
        v.push(
            "Cargo.toml: [workspace.lints.rust] unsafe_code must be \"forbid\" or \"deny\" (ADR 0011)"
                .to_owned(),
        );
    }
    Ok(v)
}

/// Top-level tables a Cargo config file in the repository may have. Every
/// other setting (`[build]` rustflags, `rustc` and wrapper overrides, `[env]`,
/// `[target.*]`, `[unstable]` and the rest) can change what the compiler
/// checks, so adding one is a reviewed change to this list.
pub const ALLOWED_CARGO_CONFIG_TABLES: &[&str] = &["alias"];

/// A Cargo config file in the repository may only define aliases, and no
/// alias may pass `--config`, a response file (`@file`), a rustflags setting, a lint
/// option whose operand names the `unsafe_code` lint (in either spelling),
/// or `--cap-lints` ([`unsafe_alias_word`]). The file
/// is parsed as TOML, so comments, escapes and `#` inside strings are
/// handled as Cargo handles them.
pub fn check_cargo_config(path: &str, source: &str) -> Vec<String> {
    let config: toml::Table = match source.parse() {
        Ok(config) => config,
        Err(e) => return vec![format!("{path}: invalid TOML: {e}")],
    };
    let mut v = Vec::new();
    for (key, value) in &config {
        if !ALLOWED_CARGO_CONFIG_TABLES.contains(&key.as_str()) {
            v.push(format!(
                "{path}: `{key}` is not allowed; a repository Cargo config may only set: {} (ADR 0011)",
                ALLOWED_CARGO_CONFIG_TABLES.join(", ")
            ));
            continue;
        }
        // Each alias on its own, so that an option's operand is the next
        // word of the same alias.
        let aliases: Vec<&toml::Value> = match value {
            toml::Value::Table(table) => table.values().collect(),
            other => vec![other],
        };
        for alias in aliases {
            let mut words = Vec::new();
            collect_words(alias, &mut words);
            if let Some(bad) = unsafe_alias_word(&words) {
                v.push(format!(
                    "{path}: `{key}` must not pass `{bad}`; aliases may not change lints, config or compiler flags"
                ));
            }
        }
    }
    v
}

/// The argument words of one alias, as Cargo passes them: a string alias is
/// split on whitespace, but each element of an array alias is one word, even
/// if it contains spaces. Table keys count too.
fn collect_words(value: &toml::Value, out: &mut Vec<String>) {
    match value {
        toml::Value::String(s) => out.extend(s.split_whitespace().map(str::to_owned)),
        toml::Value::Array(items) => {
            for item in items {
                match item {
                    toml::Value::String(s) => out.push(s.clone()),
                    other => collect_words(other, out),
                }
            }
        }
        toml::Value::Table(table) => {
            for (key, value) in table {
                out.push(key.clone());
                collect_words(value, out);
            }
        }
        _ => {}
    }
}

/// Long options that set a lint level.
const LONG_LINT_OPTIONS: &[&str] = &["--allow", "--warn", "--deny", "--forbid", "--force-warn"];

/// Short options that set a lint level. `-F` is also Cargo's `--features`,
/// which only makes the check stricter.
const SHORT_LINT_OPTIONS: &[char] = &['A', 'W', 'D', 'F'];

/// The first word of one alias that is not allowed: a response file, a
/// `--config` option, an assignment to rustflags (a word naming them with an
/// `=`, such as `build.rustflags=...`), anything naming `--cap-lints`, a `-Z`
/// option (unstable flags such as `-Z crate-attr=...` can add attributes or
/// change how config is read, and a stable build never needs them), or a
/// lint option whose operand names the `unsafe_code` lint (either spelling,
/// any case). A lint option that ends the alias is rejected too, because its
/// operand would come from a chained alias. Other words may mention the lint
/// or rustflags, so a test filter such as `unsafe_code::tests` or `rustflags`
/// is fine. Only `--config` (or `-Z`) can change Cargo's config from an
/// alias, and both are rejected wherever they appear.
fn unsafe_alias_word(words: &[String]) -> Option<&str> {
    for (i, word) in words.iter().enumerate() {
        let normalised = word.to_ascii_lowercase().replace('-', "_");
        if normalised.contains("cap_lints")
            || normalised.starts_with("__config")
            || (normalised.contains("rustflags") && word.contains('='))
            || word.starts_with('@')
        {
            return Some(word);
        }
        if let Some(attached) = lint_option_operand(word) {
            if attached.is_none() {
                return Some(word);
            }
            let attached = attached.unwrap_or_default();
            let operand = if attached.is_empty() {
                words.get(i + 1).map(String::as_str)
            } else {
                Some(attached)
            };
            match operand {
                None => return Some(word),
                Some(operand) if names_unsafe_code(operand) => return Some(word),
                Some(_) => {}
            }
        }
    }
    None
}

/// For a lint option, `Some(Some(operand))` with its attached operand
/// (`-Aunsafe_code`, `--allow=unsafe_code`), or `Some(Some(""))` when the
/// operand is the next word. `Some(None)` is a `-Z` option, which is never
/// allowed. `None` is any other word.
///
/// rustc, the lint tools and Cargo let short flags be grouped in one word,
/// and an option that takes a value takes the rest of the word or the next
/// word: `-gA unsafe_code` and `-OAunsafe_code` both allow the lint. So
/// rather than track which short flags take values, the first lint letter
/// (or `Z`) anywhere in a short-option group counts, and everything after it
/// is its operand. That can only make the check stricter.
fn lint_option_operand(word: &str) -> Option<Option<&str>> {
    if let Some(long) = word.strip_prefix("--") {
        return LONG_LINT_OPTIONS.iter().find_map(|option| {
            let rest = long.strip_prefix(&option[2..])?;
            // `--warn` is not a prefix of some other long option's name.
            if rest.is_empty() {
                Some(Some(rest))
            } else {
                rest.strip_prefix('=').map(Some)
            }
        });
    }
    let group = word.strip_prefix('-')?;
    let at = group.find(|c| c == 'Z' || SHORT_LINT_OPTIONS.contains(&c))?;
    if group[at..].starts_with('Z') {
        return Some(None);
    }
    let rest = &group[at + 1..];
    Some(Some(rest.strip_prefix('=').unwrap_or(rest)))
}

fn names_unsafe_code(text: &str) -> bool {
    text.to_ascii_lowercase()
        .replace('-', "_")
        .contains("unsafe_code")
}

/// `true` for a path whose last two components are a Cargo config file
/// (`.cargo/config.toml` or `.cargo/config`), compared ASCII
/// case-insensitively, because Windows and the other desktop OS open
/// `.CARGO/Config.toml` too.
pub fn is_cargo_config_path(path: &str) -> bool {
    let lower = path.to_ascii_lowercase();
    CARGO_CONFIG_FILES
        .iter()
        .any(|c| lower == *c || lower.ends_with(&format!("/{c}")))
}

/// `true` for a `.rs` file, in any letter case (`ffi.RS` compiles too).
pub fn is_rust_path(path: &str) -> bool {
    path.to_ascii_lowercase().ends_with(".rs")
}

/// `unsafe_code`, or `unsafe-code`, which Cargo manifests and rustc flags
/// also accept. (Inside a Rust attribute only `unsafe_code` parses; lint
/// names are case-sensitive.)
fn is_unsafe_code_lint(name: &str) -> bool {
    name.replace('-', "_") == "unsafe_code"
}

/// Tokenises Rust source. Fails closed where `proc-macro2` may read the
/// source differently from rustc: a shebang first line, and a lone `'` followed directly by a literal
/// never occurs when rustc lexes the same text (`'a` is a lifetime, `'a'` a
/// char literal), but `proc-macro2` produces it for input such as `'r"..."`,
/// which rustc reads as a lifetime and a string. Such a file is rejected
/// rather than scanned with the wrong token boundaries.
fn tokenize(source: &str) -> Result<TokenStream, String> {
    // rustc strips a first line starting with `#!` (after an optional BOM)
    // unless it is an inner attribute; proc-macro2 never does, so the two
    // would read the rest of the file differently. Only `#!` directly
    // followed by `[` (ASCII whitespace allowed) is accepted.
    let body = source.strip_prefix('\u{feff}').unwrap_or(source);
    if let Some(rest) = body.strip_prefix("#!") {
        if !rest
            .trim_start_matches([' ', '\t', '\r', '\n'])
            .starts_with('[')
        {
            return Err(
                "starts with `#!` that is not an inner attribute (a shebang line)".to_owned(),
            );
        }
    }
    let tokens = TokenStream::from_str(source).map_err(|e| e.to_string())?;
    if has_quote_before_literal(tokens.clone()) {
        return Err(
            "a `'` directly followed by a literal, which may hide tokens; add a space or rewrite it"
                .to_owned(),
        );
    }
    Ok(tokens)
}

fn has_quote_before_literal(tokens: TokenStream) -> bool {
    let tokens: Vec<TokenTree> = tokens.into_iter().collect();
    tokens.iter().enumerate().any(|(i, token)| match token {
        TokenTree::Punct(p) if p.as_char() == '\'' => {
            matches!(tokens.get(i + 1), Some(TokenTree::Literal(_)))
        }
        TokenTree::Group(group) => has_quote_before_literal(group.stream()),
        _ => false,
    })
}

/// An identifier's name without the raw prefix: `r#allow` is `allow`.
fn ident_name(ident: &proc_macro2::Ident) -> String {
    let name = ident.to_string();
    name.strip_prefix("r#").map_or(name.clone(), str::to_owned)
}

/// One attribute, inner (`#![...]`) or outer (`#[...]`): the tokens inside
/// its brackets.
struct Attribute {
    body: Vec<TokenTree>,
}

impl Attribute {
    /// `allow`, `expect` or `warn` naming `unsafe_code` among its own
    /// arguments, at any depth, either as the attribute itself or as one of
    /// the attributes of a `cfg_attr` (nested `cfg_attr` too). The level and
    /// the lint name must be in the same attribute:
    /// `cfg_attr(x, deny(unsafe_code), allow(dead_code))` does not relax it.
    fn relaxes_unsafe_code(&self) -> bool {
        meta_relaxes_unsafe_code(&self.body)
    }

    /// Exactly `forbid(...)` with `unsafe_code` as one of its top-level
    /// arguments, such as `forbid(unsafe_code)` or
    /// `forbid(missing_docs, unsafe_code, reason = "...")`.
    fn is_forbid_unsafe_code(&self) -> bool {
        let [TokenTree::Ident(name), TokenTree::Group(args)] = self.body.as_slice() else {
            return false;
        };
        if ident_name(name) != "forbid" || args.delimiter() != Delimiter::Parenthesis {
            return false;
        }
        // Split the arguments on top-level commas; one of them must be the
        // single identifier `unsafe_code`, not a tool path such as
        // `clippy::unsafe_code`, which forbids a different (unknown) lint.
        let tokens: Vec<TokenTree> = args.stream().into_iter().collect();
        tokens
            .split(|t| matches!(t, TokenTree::Punct(p) if p.as_char() == ','))
            .any(|arg| matches!(arg, [TokenTree::Ident(i)] if ident_name(i) == "unsafe_code"))
    }
}

/// One attribute's tokens, such as `allow(unsafe_code)` or
/// `cfg_attr(windows, allow(dead_code), expect(unsafe_code))`.
fn meta_relaxes_unsafe_code(meta: &[TokenTree]) -> bool {
    let Some((TokenTree::Ident(name), args)) = meta.split_first() else {
        return false;
    };
    match ident_name(name).as_str() {
        "allow" | "expect" | "warn" => {
            let Some(TokenTree::Group(group)) = args.first() else {
                return false;
            };
            let tokens: Vec<TokenTree> = group.stream().into_iter().collect();
            tokens
                .split(|t| matches!(t, TokenTree::Punct(p) if p.as_char() == ','))
                .any(lint_argument_names_unsafe_code)
        }
        "cfg_attr" => {
            let Some(TokenTree::Group(group)) = args.first() else {
                return false;
            };
            let tokens: Vec<TokenTree> = group.stream().into_iter().collect();
            // The first item is the predicate; the rest are attributes.
            tokens
                .split(|t| matches!(t, TokenTree::Punct(p) if p.as_char() == ','))
                .skip(1)
                .any(meta_relaxes_unsafe_code)
        }
        _ => false,
    }
}

/// One comma-separated argument of `allow(...)`, `expect(...)` or
/// `warn(...)`. A tool path such as `clippy::unsafe_code` names a tool's lint,
/// never rustc's built-in one, so it does not relax it. Any other argument
/// that contains the `unsafe_code` identifier counts, at any depth: that
/// covers `unsafe_code` and `r#unsafe_code`, and stays strict about forms the
/// compiler rejects or a macro rewrites, such as `$(unsafe_code)*`.
fn lint_argument_names_unsafe_code(argument: &[TokenTree]) -> bool {
    if is_tool_path(argument) {
        return false;
    }
    let mut idents = Vec::new();
    collect_idents(argument, &mut idents);
    idents.iter().any(|i| is_unsafe_code_lint(i))
}

/// `a::b`, `a::b::c` and so on: identifiers joined by `::`, with at least
/// one `::` and nothing else, not even a leading `::`.
fn is_tool_path(tokens: &[TokenTree]) -> bool {
    let mut rest = tokens;
    let mut segments = 0;
    loop {
        let Some((TokenTree::Ident(_), after)) = rest.split_first() else {
            return false;
        };
        segments += 1;
        match after {
            [] => return segments > 1,
            [TokenTree::Punct(a), TokenTree::Punct(b), tail @ ..]
                if a.as_char() == ':' && b.as_char() == ':' =>
            {
                rest = tail;
            }
            _ => return false,
        }
    }
}

fn collect_idents(tokens: &[TokenTree], out: &mut Vec<String>) {
    for token in tokens {
        match token {
            TokenTree::Ident(ident) => out.push(ident_name(ident)),
            TokenTree::Group(group) => {
                let inner: Vec<TokenTree> = group.stream().into_iter().collect();
                collect_idents(&inner, out);
            }
            _ => {}
        }
    }
}

/// The attribute starting at `tokens[i]`, if it is an inner attribute: `#`,
/// `!`, then a `[...]` group.
fn inner_attribute_at(tokens: &[TokenTree], i: usize) -> Option<Attribute> {
    match (tokens.get(i), tokens.get(i + 1), tokens.get(i + 2)) {
        (Some(TokenTree::Punct(hash)), Some(TokenTree::Punct(bang)), Some(TokenTree::Group(g)))
            if hash.as_char() == '#'
                && bang.as_char() == '!'
                && g.delimiter() == Delimiter::Bracket =>
        {
            Some(Attribute {
                body: g.stream().into_iter().collect(),
            })
        }
        _ => None,
    }
}

/// Calls `f` for every attribute in `tokens`, at any nesting depth.
fn visit_attributes(tokens: TokenStream, f: &mut dyn FnMut(&Attribute)) {
    let tokens: Vec<TokenTree> = tokens.into_iter().collect();
    for (i, token) in tokens.iter().enumerate() {
        match token {
            TokenTree::Punct(p) if p.as_char() == '#' => {
                let attribute =
                    inner_attribute_at(&tokens, i).or_else(|| match tokens.get(i + 1) {
                        Some(TokenTree::Group(g)) if g.delimiter() == Delimiter::Bracket => {
                            Some(Attribute {
                                body: g.stream().into_iter().collect(),
                            })
                        }
                        _ => None,
                    });
                if let Some(attribute) = attribute {
                    f(&attribute);
                }
            }
            TokenTree::Group(group) => visit_attributes(group.stream(), f),
            _ => {}
        }
    }
}

