//! The fixture corpus on disk (#25): `cargo xtask fixtures`, `cargo xtask
//! golden [--update]` and `cargo xtask check-testdata`.
//!
//! - **`fixtures`** builds the corpus (`palisade-fileid`'s
//!   `tests/corpus/`) into `target/fixtures/`, through the ignored
//!   `write_fixture_corpus` test, which also writes `MANIFEST`: one
//!   `<sha256> <name>` line per fixture (`nondeterministic <name>` for the
//!   one fixture whose signature is random).
//! - **`golden`** compares that manifest with the committed
//!   `testdata/golden/fixtures.txt`, and with `--update` rewrites it. A
//!   change to how any fixture is built shows up as a reviewed diff.
//! - **`check-testdata`** is the "no unknown binaries" rule: every file in
//!   the repository that starts with `MZ` (a DOS or PE executable) must
//!   have its SHA-256 listed in `testdata/manifest.txt`, with a reason.
//!   Generated fixtures are never committed, so the manifest stays short:
//!   a dropped-in PE, from anywhere, fails the check.

use std::collections::BTreeMap;
use std::path::Path;

use sha2::{Digest as _, Sha256};

/// The committed golden hashes of the generated corpus.
pub const GOLDEN: &str = "testdata/golden/fixtures.txt";
/// The committed allowlist of executable files in the repository.
pub const MANIFEST: &str = "testdata/manifest.txt";
/// Where `cargo xtask fixtures` writes the corpus.
pub const OUT_DIR: &str = "target/fixtures";

/// A parsed manifest: `name -> hash` (or `nondeterministic`).
pub type Hashes = BTreeMap<String, String>;

/// Parses `<hash> <name>` lines. Blank lines and `#` comments are skipped.
pub fn parse_hashes(text: &str, what: &str) -> Result<Hashes, String> {
    let mut out = Hashes::new();
    for (i, line) in text.lines().enumerate() {
        let line = line.trim_end_matches('\r');
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let (hash, name) = line
            .split_once(' ')
            .ok_or_else(|| format!("{what}:{}: expected `<sha256> <name>`", i + 1))?;
        let ok_hash = hash == "nondeterministic"
            || (hash.len() == 64
                && hash
                    .bytes()
                    .all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase()));
        if !ok_hash || name.is_empty() || name.contains(['/', '\\']) {
            return Err(format!("{what}:{}: bad entry `{line}`", i + 1));
        }
        if out.insert(name.to_owned(), hash.to_owned()).is_some() {
            return Err(format!("{what}:{}: `{name}` is listed twice", i + 1));
        }
    }
    Ok(out)
}

/// The differences between the committed golden hashes and a fresh build.
pub fn compare(golden: &Hashes, built: &Hashes) -> Vec<String> {
    let mut v = Vec::new();
    for (name, hash) in built {
        match golden.get(name) {
            None => v.push(format!("{name}: new fixture, not in {GOLDEN}")),
            Some(g) if g != hash => v.push(format!("{name}: hash is {hash}, {GOLDEN} has {g}")),
            Some(_) => {}
        }
    }
    for name in golden.keys() {
        if !built.contains_key(name) {
            v.push(format!("{name}: in {GOLDEN} but no longer built"));
        }
    }
    v
}

/// The golden file's text for `built`, with its header.
pub fn render_golden(built: &Hashes) -> String {
    let mut out = String::from(
        "# SHA-256 of every generated test fixture (#25). Generated by\n\
         # `cargo xtask golden --update`; do not edit by hand. Provenance:\n\
         # testdata/golden/README.md.\n",
    );
    for (name, hash) in built {
        out.push_str(&format!("{hash} {name}\n"));
    }
    out
}

/// Whether `head` starts like a DOS or PE executable.
pub fn looks_executable(head: &[u8]) -> bool {
    head.starts_with(b"MZ") || head.starts_with(b"ZM")
}

/// The allowlist: `sha256 -> reason`. Each line is `<sha256> <reason>`.
pub fn parse_manifest(text: &str) -> Result<BTreeMap<String, String>, String> {
    let mut out = BTreeMap::new();
    for (i, line) in text.lines().enumerate() {
        let line = line.trim_end_matches('\r');
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let (hash, reason) = line
            .split_once(' ')
            .ok_or_else(|| format!("{MANIFEST}:{}: expected `<sha256> <reason>`", i + 1))?;
        if hash.len() != 64
            || !hash
                .bytes()
                .all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase())
        {
            return Err(format!(
                "{MANIFEST}:{}: `{hash}` is not a lowercase SHA-256",
                i + 1
            ));
        }
        if reason.trim().is_empty() {
            return Err(format!("{MANIFEST}:{}: an entry needs a reason", i + 1));
        }
        out.insert(hash.to_owned(), reason.to_owned());
    }
    Ok(out)
}

/// Checks `files` (repository-relative paths) under `root`: every file
/// that looks like an executable must be in `allowed`. Returns violations.
pub fn check_files(
    root: &Path,
    files: &[String],
    allowed: &BTreeMap<String, String>,
) -> Result<Vec<String>, String> {
    let mut v = Vec::new();
    for path in files {
        let full = root.join(path);
        let Ok(meta) = std::fs::symlink_metadata(&full) else {
            continue; // deleted in the working tree
        };
        if !meta.is_file() {
            continue;
        }
        let mut head = [0_u8; 2];
        let n = {
            use std::io::Read as _;
            let mut f =
                std::fs::File::open(&full).map_err(|e| format!("cannot open {path}: {e}"))?;
            f.read(&mut head)
                .map_err(|e| format!("cannot read {path}: {e}"))?
        };
        if !looks_executable(&head[..n]) {
            continue;
        }
        let bytes = std::fs::read(&full).map_err(|e| format!("cannot read {path}: {e}"))?;
        let hash = hex(&Sha256::digest(&bytes));
        if !allowed.contains_key(&hash) {
            v.push(format!(
                "{path}: an executable file ({hash}) that is not in {MANIFEST}. Test fixtures are generated \
                 at test time (`cargo xtask fixtures`), never committed; real or third-party binaries are \
                 never allowed (docs/testing.md#fixtures)."
            ));
        }
    }
    Ok(v)
}

/// Lowercase hex.
pub fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    const A: &str = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";
    const B: &str = "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb";

    #[test]
    fn golden_files_parse_strictly() {
        let h = parse_hashes(
            &format!("# c\n\n{A} x.exe\nnondeterministic y.exe\r\n"),
            "g",
        )
        .unwrap();
        assert_eq!(h.len(), 2);
        assert!(parse_hashes("abc x.exe", "g").is_err());
        assert!(parse_hashes(&format!("{} x.exe", A.to_uppercase()), "g").is_err());
        assert!(parse_hashes(&format!("{A} a/x.exe"), "g").is_err());
        assert!(parse_hashes(&format!("{A} x\n{B} x"), "g").is_err());
        assert!(parse_hashes(A, "g").is_err());
    }

    #[test]
    fn every_difference_is_reported() {
        let golden: Hashes = [("a".into(), A.into()), ("gone".into(), A.into())].into();
        let built: Hashes = [("a".into(), B.into()), ("new".into(), A.into())].into();
        let v = compare(&golden, &built);
        assert_eq!(v.len(), 3, "{v:?}");
        assert!(v.iter().any(|m| m.starts_with("a: hash is")));
        assert!(v.iter().any(|m| m.starts_with("new: new fixture")));
        assert!(v.iter().any(|m| m.starts_with("gone: in")));
        assert!(compare(&built, &built).is_empty());
        let text = render_golden(&built);
        assert_eq!(parse_hashes(&text, "g").unwrap(), built);
    }

    #[test]
    fn manifests_need_hashes_and_reasons() {
        let m = parse_manifest(&format!("# c\n{A} a documented reason\n")).unwrap();
        assert_eq!(m[A], "a documented reason");
        assert!(parse_manifest(&format!("{A} ")).is_err());
        assert!(parse_manifest("xyz reason").is_err());
    }

    /// The acceptance criterion: a dropped-in unknown PE is rejected, and
    /// an allowed one or a text file is not.
    #[test]
    fn a_dropped_in_unknown_pe_is_rejected() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .join("target")
            .join(format!("xtask-testdata-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("testdata")).unwrap();
        let pe = b"MZ\x90\x00 pretend PE".to_vec();
        std::fs::write(root.join("testdata/dropped.exe"), &pe).unwrap();
        std::fs::write(root.join("testdata/notes.txt"), b"plain text").unwrap();
        std::fs::write(root.join("testdata/empty.bin"), b"").unwrap();
        let files: Vec<String> = [
            "testdata/dropped.exe",
            "testdata/notes.txt",
            "testdata/empty.bin",
            "missing",
        ]
        .iter()
        .map(|s| (*s).to_owned())
        .collect();
        let v = check_files(&root, &files, &BTreeMap::new()).unwrap();
        assert_eq!(v.len(), 1, "{v:?}");
        assert!(
            v[0].starts_with("testdata/dropped.exe: an executable file"),
            "{}",
            v[0]
        );
        let allowed = [(hex(&Sha256::digest(&pe)), "reviewed".to_owned())].into();
        assert!(check_files(&root, &files, &allowed).unwrap().is_empty());
        std::fs::remove_dir_all(&root).unwrap();
    }

    #[test]
    fn executables_are_recognised_by_their_first_bytes() {
        assert!(looks_executable(b"MZ\x90"));
        assert!(looks_executable(b"ZM"));
        assert!(!looks_executable(b"M"));
        assert!(!looks_executable(b"#!/bin/sh"));
    }
}
