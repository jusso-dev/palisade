//! `CHANGELOG.md`: generated from the Conventional Commit subjects on
//! `main` (squash-merged pull request titles), and read back for release
//! notes.
//!
//! Sections, in order: Breaking, Security, Features, Fixes, Docs, Internal.
//! A `!` before the colon puts a commit under Breaking whatever its type;
//! `security` goes under Security; `feat` under Features; `fix` under
//! Fixes; `docs` under Docs; every other allowed type (`ci`, `build`,
//! `refactor`, `test`, `chore`, `revert`) under Internal. A subject that is
//! not a Conventional Commit is listed under Internal as written, so nothing
//! is dropped silently.

/// The section headings, in the order they appear.
pub const SECTIONS: &[&str] = &[
    "Breaking", "Security", "Features", "Fixes", "Docs", "Internal",
];

/// The commit types the PR title check accepts (CONTRIBUTING.md).
pub const TYPES: &[&str] = &[
    "feat", "fix", "security", "docs", "ci", "build", "refactor", "test", "chore", "revert",
];

/// One changelog entry.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Entry {
    pub section: &'static str,
    /// The scope, if any.
    pub scope: Option<String>,
    /// The summary after the colon, with a trailing `(#123)` kept.
    pub summary: String,
}

/// Classifies one commit subject.
pub fn classify(subject: &str) -> Entry {
    let parsed = (|| {
        let (head, summary) = subject.split_once(": ")?;
        let (head, breaking) = match head.strip_suffix('!') {
            Some(h) => (h, true),
            None => (head, false),
        };
        let (kind, scope) = match head.split_once('(') {
            Some((kind, rest)) => (kind, Some(rest.strip_suffix(')')?.to_owned())),
            None => (head, None),
        };
        if !TYPES.contains(&kind) || summary.trim().is_empty() {
            return None;
        }
        let section = if breaking {
            "Breaking"
        } else {
            match kind {
                "security" => "Security",
                "feat" => "Features",
                "fix" => "Fixes",
                "docs" => "Docs",
                _ => "Internal",
            }
        };
        Some(Entry {
            section,
            scope,
            summary: summary.trim().to_owned(),
        })
    })();
    parsed.unwrap_or_else(|| Entry {
        section: "Internal",
        scope: None,
        summary: subject.trim().to_owned(),
    })
}

/// The Markdown section for one release: `## <version> - <date>` and the
/// non-empty sections, entries in commit order.
pub fn render_release(version: &str, date: &str, subjects: &[String]) -> String {
    let entries: Vec<Entry> = subjects
        .iter()
        .filter(|s| !s.trim().is_empty())
        .map(|s| classify(s))
        .collect();
    let mut out = format!("## {version} - {date}\n");
    if entries.is_empty() {
        out.push_str("\nNo changes.\n");
    }
    for section in SECTIONS {
        let items: Vec<&Entry> = entries.iter().filter(|e| e.section == *section).collect();
        if items.is_empty() {
            continue;
        }
        out.push_str(&format!("\n### {section}\n\n"));
        for e in items {
            match &e.scope {
                Some(scope) => out.push_str(&format!("- **{scope}:** {}\n", e.summary)),
                None => out.push_str(&format!("- {}\n", e.summary)),
            }
        }
    }
    out
}

/// The header every `CHANGELOG.md` starts with.
pub const HEADER: &str = "# Changelog\n\nAll notable changes, by release. Generated by `cargo xtask release prepare` from the\nConventional Commit titles of the pull requests merged to `main` (docs/releasing.md).\n";

/// Inserts a release section after the header, before every earlier
/// release. Fails if that version is already there.
pub fn insert(changelog: &str, section: &str, version: &str) -> Result<String, String> {
    if find(changelog, version).is_some() {
        return Err(format!("CHANGELOG.md already has a section for {version}"));
    }
    let body = changelog
        .strip_prefix(HEADER)
        .unwrap_or_else(|| changelog.strip_prefix("# Changelog\n").unwrap_or(changelog));
    let body = body.trim_start_matches('\n');
    let mut out = format!("{HEADER}\n{section}");
    if !body.is_empty() {
        out.push('\n');
        out.push_str(body);
    }
    if !out.ends_with('\n') {
        out.push('\n');
    }
    Ok(out)
}

/// The byte range of `version`'s section, from its `## ` line to the next
/// `## ` line or the end.
fn find(changelog: &str, version: &str) -> Option<(usize, usize)> {
    let heading = format!("## {version} ");
    let mut offset = 0;
    let mut start = None;
    for line in changelog.split_inclusive('\n') {
        if let Some(begin) = start {
            if line.starts_with("## ") {
                return Some((begin, offset));
            }
        } else if line.starts_with(&heading) || line.trim_end() == format!("## {version}") {
            start = Some(offset);
        }
        offset += line.len();
    }
    start.map(|begin| (begin, changelog.len()))
}

/// The release notes for `version`: its section without the `## ` heading.
pub fn excerpt(changelog: &str, version: &str) -> Result<String, String> {
    let (start, end) = find(changelog, version)
        .ok_or_else(|| format!("CHANGELOG.md has no section for {version}"))?;
    let section = &changelog[start..end];
    let body = section.split_once('\n').map_or("", |(_, rest)| rest);
    Ok(format!("{}\n", body.trim()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn classifies_conventional_commits() {
        let e = classify("feat(policy): add publisher rules (#12)");
        assert_eq!(
            (e.section, e.scope.as_deref(), e.summary.as_str()),
            ("Features", Some("policy"), "add publisher rules (#12)")
        );
        assert_eq!(classify("fix: handle renamed files").section, "Fixes");
        assert_eq!(
            classify("security(agent): drop privileges").section,
            "Security"
        );
        assert_eq!(classify("docs: explain").section, "Docs");
        for internal in [
            "ci: x",
            "build(deps): x",
            "refactor: x",
            "test: x",
            "chore: x",
            "revert: x",
        ] {
            assert_eq!(classify(internal).section, "Internal", "{internal}");
        }
        assert_eq!(classify("feat(policy)!: rename rules").section, "Breaking");
        assert_eq!(classify("fix!: change exit codes").section, "Breaking");
        let odd = classify("Merge branch 'x'");
        assert_eq!(
            (odd.section, odd.summary.as_str()),
            ("Internal", "Merge branch 'x'")
        );
        assert_eq!(classify("feature: no").section, "Internal");
        assert_eq!(classify("feat(x: unclosed").summary, "feat(x: unclosed");
    }

    #[test]
    fn renders_sections_in_order() {
        let subjects: Vec<String> = [
            "ci: speed up",
            "feat(fileid): parse things (#1)",
            "fix(agent): crash (#2)",
            "feat!: new config format (#3)",
            "security: patch (#4)",
            "docs: readme",
            "",
        ]
        .iter()
        .map(|s| (*s).to_owned())
        .collect();
        assert_eq!(
            render_release("0.2.0", "2026-12-01", &subjects),
            "## 0.2.0 - 2026-12-01\n\n### Breaking\n\n- new config format (#3)\n\n### Security\n\n- patch (#4)\n\n\
             ### Features\n\n- **fileid:** parse things (#1)\n\n### Fixes\n\n- **agent:** crash (#2)\n\n\
             ### Docs\n\n- readme\n\n### Internal\n\n- speed up\n"
        );
        assert_eq!(
            render_release("0.1.1", "d", &[]),
            "## 0.1.1 - d\n\nNo changes.\n"
        );
    }

    #[test]
    fn inserts_newest_first_and_extracts_notes() {
        let first = insert(
            "",
            &render_release("0.1.0", "2026-11-30", &["feat: a".into()]),
            "0.1.0",
        )
        .unwrap();
        assert!(first.starts_with(HEADER));
        let second = insert(
            &first,
            &render_release("0.2.0-rc.1", "2026-12-01", &["fix: b".into()]),
            "0.2.0-rc.1",
        )
        .unwrap();
        let rc = second.find("## 0.2.0-rc.1").unwrap();
        let old = second.find("## 0.1.0").unwrap();
        assert!(rc < old);
        assert_eq!(
            excerpt(&second, "0.2.0-rc.1").unwrap(),
            "### Fixes\n\n- b\n"
        );
        assert_eq!(excerpt(&second, "0.1.0").unwrap(), "### Features\n\n- a\n");
        assert!(
            excerpt(&second, "0.2.0").is_err(),
            "0.2.0 is not 0.2.0-rc.1"
        );
        assert!(insert(&second, "## 0.1.0 - x\n", "0.1.0").is_err());
    }
}
